void draw_icon_ascii(const char **icon, NSRect r) {
    [[NSColor blackColor] setFill];
    CGFloat px = 1.0;
    CGFloat ox = r.origin.x + (r.size.width  - 32*px) / 2;
    CGFloat oy = r.origin.y + (r.size.height - 32*px) / 2;
    for (int row = 0; row < 32; row++) {
        const char *line = icon[row];
        if (!line) continue;
        for (int col = 0; col < 32 && line[col]; col++) {
            if (line[col] == '#')
                NSRectFill(NSMakeRect(ox + col*px, oy + row*px, px, px));
        }
    }
}
